/* Swap Google Fonts for the same files, served from this origin.

   Before: preconnect, preconnect, then a render-blocking stylesheet from
   fonts.googleapis.com, and only once that arrives does the browser learn to
   fetch woff2 files from fonts.gstatic.com. Two extra hosts, two DNS lookups,
   two TLS handshakes and a round trip, all ahead of first paint, on every
   page of the site.

   After: the same @font-face rules inline in the stylesheet that is already
   there, pointing at the same woff2 binaries on the same origin as the page.
   No third party in the critical path, and nothing to look at differently --
   these are Google's own files with Google's own unicode-ranges, so glyphs,
   metrics and fallback behaviour are identical by construction rather than by
   judgement. build/verify-fonts.mjs measures that claim rather than trusting
   it.

   font-display:swap is preserved from the original request, so text still
   paints immediately in the fallback and swaps when the face arrives.

   Re-runnable: the generated block is fenced by markers, so regenerating the
   faces and applying this again replaces the block rather than stacking a
   second copy. That matters, because getting the subsets right took two
   goes -- Google writes the subset name in a comment BEFORE each @font-face,
   and the first attempt paired every block with the next one's label.      */

import fs from 'fs';

const FILE = 'src/index.html';
const START = '/* === self-hosted typefaces: generated by build/fonts-selfhost.mjs === */';
const END = '/* === end self-hosted typefaces === */';

let s = fs.readFileSync(FILE, 'utf8');
const before = s.length;
const log = [];
let failed = 0;

const crlf = t => t.replace(/\r?\n/g, '\r\n');

/* ---- 1. remove the three Google Fonts links ---- */
{
  const re = /[ \t]*<link rel="preconnect" href="https:\/\/fonts\.googleapis\.com">\r?\n[ \t]*<link rel="preconnect" href="https:\/\/fonts\.gstatic\.com" crossorigin>\r?\n[ \t]*<link href="https:\/\/fonts\.googleapis\.com\/css2\?[^"]*" rel="stylesheet">\r?\n/;
  if (re.test(s)) { s = s.replace(re, ''); log.push('ok    two preconnects and the blocking stylesheet removed'); }
  else if (/fonts\.googleapis\.com/.test(s)) { log.push('FAIL  a Google Fonts reference is present but did not match the expected three lines'); failed++; }
  else log.push('ok    no Google Fonts links present');
}

/* ---- 2. drop whatever a previous run inserted ---- */
{
  const a = s.indexOf(START), b = s.indexOf(END);
  if (a >= 0 && b > a) {
    s = s.slice(0, a) + s.slice(b + END.length).replace(/^\r?\n/, '');
    log.push('ok    previous generated block removed');
  } else if (a >= 0 || b >= 0) {
    log.push('FAIL  only one of the two markers is present; refusing to guess');
    failed++;
  }
  if ((s.match(/@font-face/g) || []).length) {
    log.push(`FAIL  ${(s.match(/@font-face/g) || []).length} unfenced @font-face rules already in the page`);
    failed++;
  }
}

/* ---- 3. insert at the top of the existing stylesheet ---- */
if (!failed) {
  const face = fs.readFileSync('build/fonts-face.css', 'utf8').trim();
  const open = s.indexOf('<style>');
  if (open < 0) { log.push('FAIL  no <style> block'); failed++; }
  else {
    const header = `
/* Generated from the exact Google Fonts request this site used to make, so
   the files and their unicode-ranges are identical -- latin loads for English
   text and latin-ext only if a character needs it. Do not hand-edit: re-run
   build/fonts-selfhost.mjs and then this patch.

   Abhaya Libre 500 and Manrope 800 are absent on purpose. 500 is in the old
   URL but no rule uses it, and the site's two Manrope font-weight:800 rules
   have always been synthesised by the browser -- shipping the real face would
   change how they look, which is a design decision and not a performance
   one. */
`;
    s = s.slice(0, open + '<style>'.length)
      + crlf('\n' + START + header + face + '\n' + END + '\n')
      + s.slice(open + '<style>'.length);
    log.push(`ok    ${(face.match(/@font-face/g) || []).length} @font-face rules inlined (${(face.length / 1024).toFixed(1)} KB)`);
  }
}

if (failed) {
  console.log(log.join('\n'));
  console.log(`\n${failed} step(s) failed, ${FILE} not written`);
  process.exitCode = 1;
} else {
  fs.writeFileSync(FILE, s);
  console.log(log.join('\n'));
  console.log(`\n${FILE}: ${before} -> ${s.length} chars`);
}
