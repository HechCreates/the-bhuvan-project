/* Visual Journey: copy the photographs in and write content/journey.yml.

   The categorisation lives in CATS below as index ranges against the folder's
   sorted order -- the same numbering as the contact sheets in build/vj-sheets.mjs,
   so a disputed photograph can be looked up by number.

   The sources are already small (400-1000px on the long edge, 9MB for all 214),
   so they are copied rather than resized; there is no larger original to draw on. */
import fs from 'fs';
import path from 'path';

const SRC = 'Visual Journey (Gallery Page)';
const OUT = 'site/images/journey';
const YML = 'site/content/journey.yml';

/* Which photograph went where, by its number in the folder's sorted order --
   the same numbering the contact sheets carry, so any one of them can be
   looked up and argued with. Every index 1..N must appear exactly once; the
   assertion below is what makes a transcription slip impossible to miss. */
const MEMBERS = {
  'floral-faunal': [1, 3, 8, 9, 13, 14, 18, 19, 20, 21, 22, 25, 26, 27, 28, 31, 33, 38, 40, 50,
    56, 61, 62, 63, 66, 68, 69, 70, 73, 76, 81, 82, 84, 86, 88, 94, 95, 96, 97, 100,
    111, 112, 118, 129, 151, 155, 159, 160, 161, 162, 163, 164, 165, 166, 167, 168, 172, 173, 174, 178,
    180, 182, 192, 196, 198, 199, 200, 201, 202, 204, 209, 210, 213],
  cultural: [23, 24, 30, 32, 35, 36, 37, 39, 41, 42, 44, 45, 48, 49, 51, 53, 54, 55, 60, 64,
    65, 71, 75, 77, 78, 79, 80, 93, 98, 99, 103, 105, 106, 107, 108, 109, 110, 113, 119, 120,
    122, 123, 124, 131, 135, 136, 137, 138, 141, 142, 143, 144, 147, 148, 150, 157, 169, 170, 188, 189,
    190, 191, 195, 205, 208, 214],
  geographical: [2, 5, 7, 11, 12, 15, 34, 46, 47, 52, 57, 67, 72, 83, 89, 90, 91, 92, 101, 102,
    114, 115, 121, 125, 126, 127, 128, 130, 132, 133, 134, 140, 146, 152, 156, 171, 185, 186, 187, 193,
    203, 206, 207, 212],
  ecological: [4, 6, 10, 16, 17, 29, 85, 104, 145, 149, 153, 154, 158, 175, 176, 177, 183, 194, 197],
  geological: [43, 58, 59, 74, 87, 116, 117, 139, 179, 181, 184, 211],
};

/* The order the template draws them, and the four picked for each grid mosaic
   (1-based indices into the sorted folder). The first is the large tile. */
const CATS = [
  ['geographical',  'Geographical Diversity',    [83, 134, 12, 115]],
  ['cultural',      'Cultural Diversity',        [120, 135, 170, 142]],
  ['geological',    'Geological Diversity',      [184, 116, 117, 211]],
  ['ecological',    'Ecological Diversity',      [177, 197, 10, 154]],
  ['floral-faunal', 'Floral and Faunal Diversity', [9, 26, 168, 76]],
];

/* The client's filenames are the captions. These four are plain typos. */
const FIX = {
  'Elephats of Jim Corbett': 'Elephants of Jim Corbett',
  'Emerald Endemisim': 'Emerald Endemism',
  'Scorpian King': 'Scorpion King',
  'Silver ribbion': 'Silver ribbon',
};

const NAMELESS = s => /^IMG[_0-9]/i.test(s) || s === 'v' || s === 'no caption';
const slug = s => s.toLowerCase().replace(/['’]/g, '').replace(/[^a-z0-9]+/g, '-')
  .replace(/^-|-$/g, '').slice(0, 60);

const files = fs.readdirSync(SRC).filter(f => f.endsWith('.webp')).sort();

/* every photograph in exactly one category, and no index invented */
const A = [];
for (const [cat, idx] of Object.entries(MEMBERS)) for (const n of idx) {
  if (n < 1 || n > files.length) { console.log(`FAIL: index ${n} is out of range`); process.exit(1); }
  if (A[n - 1]) { console.log(`FAIL: index ${n} is in both ${A[n - 1]} and ${cat}`); process.exit(1); }
  A[n - 1] = cat;
}
const missing = [];
for (let i = 0; i < files.length; i++) if (!A[i]) missing.push(i + 1);
if (missing.length) { console.log(`FAIL: uncategorised: ${missing.join(', ')}`); process.exit(1); }
console.log(`  all ${files.length} photographs categorised exactly once`);

fs.rmSync(OUT, { recursive: true, force: true });
fs.mkdirSync(OUT, { recursive: true });

const byCat = {};
const seen = new Set();
const pickOf = new Map();                       // 1-based index -> slug
files.forEach((f, i) => {
  const stem = f.replace(/\.webp$/, '');
  const cat = A[i];
  let s = NAMELESS(stem) ? `${cat}-${String(i + 1).padStart(3, '0')}` : slug(stem);
  while (seen.has(s)) s += '-b';
  seen.add(s);
  fs.copyFileSync(path.join(SRC, f), path.join(OUT, `${s}.webp`));
  (byCat[cat] ||= []).push({ file: `${s}.webp`, caption: NAMELESS(stem) ? '' : (FIX[stem] || stem) });
  pickOf.set(i + 1, `${s}.webp`);
});

const esc = s => /[:#'"\[\]{}&*?|<>=!%@`]|^\s|\s$/.test(s) ? JSON.stringify(s) : s;
let y = `# Visual Journey. Generated by build/journey-assets.mjs -- the categories
# come from going through every photograph in "${SRC}".
#
# caption: "" means the source file had no name of its own (IMG_1234 and the
# like); those stay uncaptioned in the popup, as the client asked.
categories:\n`;

for (const [key, title, picks] of CATS) {
  const list = byCat[key] || [];
  const pickFiles = picks.map(n => {
    const f = pickOf.get(n);
    if (!f) { console.log(`FAIL: pick ${n} is out of range`); process.exit(1); }
    if (!list.some(p => p.file === f)) { console.log(`FAIL: pick ${n} (${f}) is not in ${key}`); process.exit(1); }
    return f;
  });
  y += `  - key: ${key}\n    title: ${esc(title)}\n    picks:\n`;
  pickFiles.forEach(f => { y += `      - ${f}\n`; });
  y += `    photos:\n`;
  list.forEach(p => { y += `      - file: ${p.file}\n        caption: ${p.caption ? esc(p.caption) : '""'}\n`; });
  console.log(`  ${title.padEnd(28)} ${String(list.length).padStart(3)} photographs`);
}

fs.writeFileSync(YML, y);
console.log(`\n  ${files.length} copied to ${OUT}`);
console.log(`  ${YML} written`);
